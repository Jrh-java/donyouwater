import * as Cesium from 'cesium'
function loadStaticWall(viewer) {
    var imageUrl = './testWall.png';
    let wallEntity
    coordinateTotal.forEach(coordinate => {
        let positions = Cesium.Cartesian3.fromDegreesArray(coordinate);
         wallEntity = viewer.entities.add({
            name: "立体墙效果",
            wall: {
                positions: positions,
                // 设置高度
                maximumHeights: new Array(positions.length).fill(200),
                minimunHeights: new Array(positions.length).fill(0),
                // 扩散墙材质
                material: new Cesium.ImageMaterialProperty({
                    image: imageUrl, // 图片路径
                    transparent: true, // 如果图片有透明背景，可以设置为 true
                    repeat: new Cesium.Cartesian2(1, 4)
                })
            }
        })
    });
    // let index=0
    // setInterval(() => {
    //     //取index的尾数
    //     index=index%10
    //     imageUrl=`./animationImg/${index}.png`
    //     wallEntity.wall.material.image = imageUrl;
    //     index++
    // }, 1000);
    viewer.zoomTo(wallEntity);
}

